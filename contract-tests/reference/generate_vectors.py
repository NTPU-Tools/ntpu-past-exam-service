def bcrypt_vectors():
    out = []
    for password, rounds in [("correct horse", 4), ("密碼🔒", 4), ("a" * 72, 4), ("", 4), ("correct horse", 12)]:
        hashed = bcrypt.hashpw(password.encode(), bcrypt.gensalt(rounds)).decode()
        candidates = {password, password + "x", password.upper(), "a" * 72 + "b", "wrong"}
        for candidate in sorted(candidates):
            out.append({"hash": hashed, "password": candidate,
                        "matches": bcrypt.checkpw(candidate.encode(), hashed.encode())})
    two_a = bcrypt.hashpw(b"legacy", bcrypt.gensalt(4)).decode().replace("$2b$", "$2a$", 1)
    out.append({"hash": two_a, "password": "legacy", "matches": bcrypt.checkpw(b"legacy", two_a.encode())})
    write("bcrypt.json", {"cases": out, "generated_hash_prefix": "$2b$12$"})


